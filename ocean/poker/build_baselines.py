"""Export a pinned Fullhouse artifact to C and build native benchmark policies.

Run with the isolated benchmark Python (NumPy and eval7 required only here/tests).
No Python, BLAS, model loading, allocations or threads in native decisions.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
COMMIT = "e504793d480b1b975f25258d25939b45c6dbd5a4"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, default=ROOT / 'build/poker/external/fullhouse-bot')
    parser.add_argument('--output', type=Path, default=ROOT / 'build/poker')
    parser.add_argument('--cc', default=os.environ.get('CC') or shutil.which('clang-19') or 'cc',
                        help='C compiler command (default: CC, clang-19, then cc)')
    args = parser.parse_args()
    source = args.source.resolve()
    commit = subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip()
    if commit != COMMIT:
        raise SystemExit(f'Expected pinned Fullhouse commit {COMMIT}, got {commit}')
    sys.path.insert(0, str(source))
    from bot import bot
    build = args.output.resolve()
    build.mkdir(parents=True,exist_ok=True)
    header = build / 'fullhouse_weights.h'
    arrays = {}
    artifacts = {}
    for name in ('deep_cfr_model.npz', 'preflop_equity.npz'):
        path = source / 'data' / name
        artifacts[name] = {'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'bytes': path.stat().st_size}
        with np.load(path, allow_pickle=False) as data:
            arrays.update({k: data[k].astype(np.float32).flatten() for k in data.files})
    expected = {'trunk_w0':256*51, 'trunk_w1':256*256, 'val_w0':128*256, 'adv_w0':128*256}
    assert all(arrays[k].size == n for k, n in expected.items())
    assert all(np.isfinite(a).all() for a in arrays.values())
    ranges = [bot._PF_TIER1, bot._PF_TIER2, bot._PF_TIER3,
              bot._PF_CALL_TIGHT, bot._PF_CALL_MEDIUM, bot._PF_CALL_WIDE]
    push = []
    for hi in '23456789TJQKA':
        for lo in '23456789TJQKA':
            for suited in (False, True):
                cls = hi + lo + ('' if hi == lo else 's' if suited else 'o')
                push.append(sum(1 << i for i, r in enumerate(ranges) if cls in r))
    with header.open('w') as out:
        out.write('// Generated by ocean/poker/build_baselines.py; MIT Advit Arora.\n')
        for key, a in arrays.items():
            values = [float(v).hex() + 'f' for v in a]
            out.write(f'static const float fh_{key}[{len(a)}] = {{\n')
            for i in range(0, len(a), 8): out.write(','.join(values[i:i+8]) + ',\n')
            out.write('};\n')
        out.write('static const unsigned char fh_push_ranges[338] = {' + ','.join(map(str,push)) + '};\n')
    commands = []
    for players in (2, 6):
        flags = shlex.split(args.cc) + ['-O3', '-march=native', '-ffp-contract=off', '-std=c11', '-Wall', '-Wextra',
                 f'-DPOKER_PLAYERS={players}', f'-DPOKER_FULLHOUSE_MODEL="{header}"']
        # Keep assertions enabled in the evaluation build.
        for src, extra, dest in [('native.c', ['-shared','-fPIC'],f'libpoker_fullhouse{players}.so'),
                                  ('benchmark.c', [], f'baseline_bench{players}'),
                                  ('benchmark_policy.c', [], f'policy_bench{players}')]:
            cmd = flags + extra + [str(ROOT/'ocean/poker'/src), '-lm', '-o', str(build/dest)]
            subprocess.run(cmd, check=True)
            commands.append(cmd)
    manifest = {'source':'https://github.com/advitrocks9/fullhouse-bot', 'commit':commit,
                'compiler':subprocess.check_output(shlex.split(args.cc) + ['--version'], text=True).splitlines()[0],
                'artifacts':artifacts, 'float_weight_bytes':sum(a.nbytes for a in arrays.values()),
                'commands':commands,
                'binaries':{p.name:hashlib.sha256(p.read_bytes()).hexdigest()
                            for p in build.glob('libpoker_fullhouse*.so')}}
    (build/'fullhouse-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({k:v for k,v in manifest.items() if k != 'commands'},indent=2))


if __name__ == '__main__': main()
