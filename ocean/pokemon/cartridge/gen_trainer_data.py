"""Cartridge tables for the single-player (trainer AI) mode of our pkmn/engine fork (2026-10-30).

Reads a pret/pokered checkout and writes src/lib/gen1/data/trainer.zig in the engine fork:
- EFFECTS, POWERS, TYPES: each move's cartridge effect constant (move_effect_constants.asm order), base power and
  type, which the trainer AI's move-choice layers test;
- TYPE_EFFECTS: the type matchup list in its original order (AIGetTypeEffectiveness uses the first entry matching the
  move type and either of the target's types, so order matters);
- CLASSES: per trainer class the AI routine, its per-Pokemon use count (ai_pointers.asm) and its move-choice layers
  (move_choices.asm).
Usage: python3 ocean/pokemon/cartridge/gen_trainer_data.py POKERED_DIR OUT.zig
"""
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1])


def read(path):
    return (root / path).read_text()


def names(path):
    return [m for m in re.findall(r'^\s*const (\w+)', read(path), re.M)]


effects = names('constants/move_effect_constants.asm')
rows = re.findall(r'^\s*move \w+,\s*(\w+),\s*(\d+),\s*(\w+),', read('data/moves/moves.asm'), re.M)
moves = [r[0] for r in rows]
assert len(moves) == 165, len(moves)

ENGINE_TYPES = {'NORMAL': 'Normal', 'FIGHTING': 'Fighting', 'FLYING': 'Flying', 'POISON': 'Poison',
                'GROUND': 'Ground', 'ROCK': 'Rock', 'BUG': 'Bug', 'GHOST': 'Ghost', 'FIRE': 'Fire', 'WATER': 'Water',
                'GRASS': 'Grass', 'ELECTRIC': 'Electric', 'PSYCHIC_TYPE': 'Psychic', 'ICE': 'Ice',
                'DRAGON': 'Dragon'}
VALUE = {'SUPER_EFFECTIVE': 20, 'NOT_VERY_EFFECTIVE': 5, 'NO_EFFECT': 0}
matchups = re.findall(r'db (\w+),\s*(\w+),\s*(\w+)', read('data/types/type_matchups.asm'))

counts = re.findall(r'dbw (\d+), (\w+)AI', read('data/trainers/ai_pointers.asm'))
layers = re.findall(r'^\s*move_choices\s*([\d, ]*)', read('data/trainers/move_choices.asm'), re.M)
routines = sorted({r for _, r in counts if r != 'Generic'})
assert len(counts) == len(layers) == 47, (len(counts), len(layers))

out = ['// Generated by PufferLib ocean/pokemon/cartridge/gen_trainer_data.py from pret/pokered. Do not edit.',
       'const gen1 = @import("../data.zig");', '', 'const Type = gen1.Type;', '',
       '/// Cartridge move effect constant of each move (index = move id; 0 = no move).',
       'pub const EFFECTS = [_]u8{ 0, ' + ', '.join(str(effects.index(e)) for e in moves) + ' };',
       '/// Cartridge base power of each move (fixed-damage moves have 1).',
       'pub const POWERS = [_]u8{ 0, ' + ', '.join(r[1] for r in rows) + ' };',
       '/// Cartridge type of each move.',
       'pub const TYPES = [_]Type{ .Normal, ' + ', '.join('.' + ENGINE_TYPES[r[2]] for r in rows) + ' };', '']
for name in ('ATTACK_UP1_EFFECT', 'BIDE_EFFECT', 'ATTACK_UP2_EFFECT', 'POISON_EFFECT', 'SLEEP_EFFECT',
             'PARALYZE_EFFECT', 'EFFECT_01', 'SUPER_FANG_EFFECT', 'SPECIAL_DAMAGE_EFFECT', 'FLY_EFFECT'):
    out.append(f'pub const {name} = {effects.index(name)};')
out += ['', '/// The type matchup list in cartridge order: move type, target type, multiplier x10.',
        'pub const TYPE_EFFECTS = [_]struct { Type, Type, u8 }{']
out += [f'    .{{ .{ENGINE_TYPES[a]}, .{ENGINE_TYPES[d]}, {VALUE[v]} }},' for a, d, v in matchups]
out += ['};', '', '/// Trainer class routines (trainer_ai.asm); None does nothing.',
        'pub const Routine = enum(u8) { None, ' + ', '.join(routines) + ' };', '',
        'pub const Class = struct { routine: Routine, uses: u8, layers: u4 };', '',
        '/// Index = trainer class id - 1 (trainer_constants.asm order).', 'pub const CLASSES = [_]Class{']
for (count, routine), layer in zip(counts, layers):
    mask = sum(1 << (int(x) - 1) for x in re.findall(r'\d', layer))
    out.append(f'    .{{ .routine = .{"None" if routine == "Generic" else routine}, .uses = {count}, '
               f'.layers = 0b{mask:04b} }},')
out += ['};', '']
pathlib.Path(sys.argv[2]).write_text('\n'.join(out))
print(f'{len(moves)} moves, {len(matchups)} type matchups, {len(counts)} classes, routines {routines}')
