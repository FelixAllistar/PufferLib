#!/usr/bin/env python3
"""Generate smogon_sets.inc: every exact 4-move Smogon Gen 1 set per species, for the set-match log.

Each named set in data/smogon-gen1.json (all formats) is expanded over its slash options. Sets with a
move the species cannot learn here, a repeated move or a forbidden combination are dropped. Moves are
stored sorted so a drafted set matches by sorted comparison. Usage: python3 generate_smogon_sets.py
"""
import itertools, json, re
from pathlib import Path

HERE = Path(__file__).resolve().parent
norm = lambda s: re.sub(r'[^a-z0-9]', '', s.lower())
rules = json.loads((HERE / 'data/freepick.json').read_text())
smogon = json.loads((HERE / 'data/smogon-gen1.json').read_text())
move_id = {norm(m['name']): m['id'] for m in rules['moves'] if m['id']}
learnable = {s['id']: set(s['moves']) for s in rules['species'] if s['id']}
species_id = {norm(s['name']): s['id'] for s in rules['species'] if s['id']}
forbidden = [(f['species'], set(f['moves'])) for f in rules['forbidden']]

sets = {s: set() for s in learnable}
for name, formats in smogon.items():
    sid = species_id.get(norm(name))
    if sid is None: continue  # Mewtwo and Mew are not in the 149-species engine
    for named in formats.values():
        for entry in named.values():
            slots = [[move_id.get(norm(m)) for m in (x if isinstance(x, list) else [x])] for x in entry['moves']]
            for combo in itertools.product(*slots):
                moves = set(combo)
                if len(combo) != 4 or None in moves or len(moves) != 4 or not moves <= learnable[sid]: continue
                if any(f_sid == sid and f_moves <= moves for f_sid, f_moves in forbidden): continue
                sets[sid].add(tuple(sorted(moves)))

offsets, rows = [0], []
for sid in range(1, 150):
    rows += sorted(sets[sid])
    offsets.append(len(rows))
lines = ['// Generated by generate_smogon_sets.py from data/smogon-gen1.json; do not edit.',
         f'// {len(rows)} exact 4-move sets over all Smogon formats, moves sorted ascending.',
         f'#define PK_SMOGON_SET_COUNT {len(rows)}',
         'static const uint16_t pk_smogon_set_offset[151] = {0,' + ','.join(map(str, offsets)) + '};',
         'static const uint8_t pk_smogon_sets[PK_SMOGON_SET_COUNT][4] = {']
lines += ['    {' + ','.join(map(str, r)) + '},' for r in rows] + ['};', '']
(HERE / 'smogon_sets.inc').write_text('\n'.join(lines))
print(f'{len(rows)} sets, {sum(1 for s in sets.values() if s)} species with at least one set')
