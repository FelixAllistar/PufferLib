// Base stats for the pokemon3 observation (2026-11-06): writes engine/src/basestats.rs, the Gen 3 base stats of every
// species poke-engine names (src/pokemon.rs PokemonName) that exists in Gen 3, from Showdown's own data. The
// observation shows the opponent's stats as a player can estimate them (base stats at the shown level, 85 EVs, 31 IVs,
// neutral nature: how Gen 3 random battles build most sets), not their real ones; the Showdown bridge can do the same.
// Usage: NODE_PATH=build/pokemon/showdown_server/node_modules node ocean/pokemon3/gen_basestats.js POKE_ENGINE_SRC
const fs = require('fs'), path = require('path');
const {Dex} = require('pokemon-showdown');
const src = fs.readFileSync(path.join(process.argv[2], 'src/pokemon.rs'), 'utf8');
const names = new Set([...src.slice(src.indexOf('PokemonName {')).matchAll(/^\s+([A-Z0-9]+),$/gm)].map(m => m[1]));
const arms = [];
for (const s of Dex.mod('gen3').species.all()) {
  if (!s.exists || s.num < 1 || s.num > 386 || (s.isNonstandard && s.isNonstandard !== 'Past')) continue;
  const n = s.id.toUpperCase();
  if (!names.has(n)) continue;
  const b = s.baseStats;
  arms.push(`        PokemonName::${n} => [${b.hp}, ${b.atk}, ${b.def}, ${b.spa}, ${b.spd}, ${b.spe}],`);
}
// Unown's letters are cosmetic formes (not separate species in the data); poke-engine names each one.
const unown = Dex.mod('gen3').species.get('unown').baseStats;
for (const n of names) if (/^UNOWN.+/.test(n)) arms.push(`        PokemonName::${n} => [${Object.values(unown).join(', ')}],`);
const out = path.join(__dirname, 'engine/src/basestats.rs');
fs.writeFileSync(out, `// Generated by ocean/pokemon3/gen_basestats.js from Showdown's Gen 3 species data. Do not edit.\n` +
  `use poke_engine::pokemon::PokemonName;\n\n/// Gen 3 base stats [hp, atk, def, spa, spd, spe], or None for a species not in Gen 3.\n` +
  `pub fn base(x: PokemonName) -> Option<[u16; 6]> {\n    Some(match x {\n${arms.join('\n')}\n        _ => return None,\n    })\n}\n`);
console.log(`${out}: ${arms.length} species`);
