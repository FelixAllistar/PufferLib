"""Ability and item vocabularies for the pokemon9 observation (2026-10-30).

Reads a positions file (build_positions.js) and writes engine/src/vocab.rs: a slot for every ability and item that
appears in Gen 9 random battles (204 abilities and 60 items in 50K battles), most common first, plus a last "other"
slot. Names poke-engine does not define (it reads them as no item: Leppa Berry and Scope Lens on 2026-10-30;
Light Clay was added to the engine) are listed and left out. Usage: python3 ocean/pokemon9/gen_vocab.py POSITIONS POKE_ENGINE_SRC
"""
import collections
import pathlib
import re
import sys

src = pathlib.Path(sys.argv[2]) / 'src' / 'genx'
defined = {name: set(re.findall(r'^\s+([A-Z][A-Z0-9]*),$', (src / f'{name}.rs').read_text(), re.M))
           for name in ('abilities', 'items')}

abilities, items = collections.Counter(), collections.Counter()
for i, line in enumerate(open(sys.argv[1])):
    if i >= 50000:
        break
    for side in line.split('/')[:2]:
        for mon in side.split('=')[:6]:
            fields = mon.split(',')
            abilities[fields[8]] += 1
            items[fields[10]] += 1


def table(name, enum, counts):
    missing = [k for k in counts if k not in defined[{'ability': 'abilities', 'item': 'items'}[name]]]
    if missing:
        print(f'not in poke-engine, left out: {missing}')
    names = [k for k, _ in counts.most_common() if k not in missing]
    arms = '\n'.join(f'        {enum}::{k} => {i},' for i, k in enumerate(names))
    return (f'pub const {name.upper()}_SLOTS: usize = {len(names) + 1};\n\n'
            f'pub fn {name}_slot(x: {enum}) -> usize {{\n    match x {{\n{arms}\n'
            f'        _ => {len(names)},\n    }}\n}}\n')


out = pathlib.Path(__file__).parent / 'engine' / 'src' / 'vocab.rs'
out.write_text('// Generated by ocean/pokemon9/gen_vocab.py from Gen 9 random-battle positions. Do not edit.\n'
               'use poke_engine::engine::abilities::Abilities;\nuse poke_engine::engine::items::Items;\n\n'
               + table('ability', 'Abilities', abilities) + '\n' + table('item', 'Items', items))
print(f'{out}: {len(abilities)} abilities, {len(items)} items')
