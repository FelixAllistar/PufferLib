// Preserve the delivered two-mesh static pose, including its open-door transform.
// From ocean/swat: clang tools/import_motel_cabinet.c -lm -o <temporary importer>.
#include "../vendor/cgltf_private.h"
#include <assert.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
int main(void) {
    const char* file="power_box_01_rear_centered_1k.glb";
    char path[256];snprintf(path,sizeof(path),"assets/environment/motel_props/%s",file);
    cgltf_options options={0};cgltf_data* data=NULL;
    assert(cgltf_parse_file(&options,path,&data)==cgltf_result_success);
    assert(cgltf_load_buffers(&options,data,path)==cgltf_result_success && cgltf_validate(data)==cgltf_result_success);
    assert(data->materials_count==1 && data->skins_count==0 && data->animations_count==0);
    size_t vertices_count=0,indices_count=0,meshes=0;
    for(size_t n=0;n<data->nodes_count;n++)if(data->nodes[n].mesh) {
        cgltf_mesh* mesh=data->nodes[n].mesh;assert(mesh->primitives_count==1);meshes++;
        cgltf_primitive* p=mesh->primitives;
        assert(p->indices && p->type==cgltf_primitive_type_triangles && p->material==data->materials);
        const cgltf_accessor* positions=cgltf_find_accessor(p,cgltf_attribute_type_position,0);assert(positions);
        vertices_count+=positions->count;indices_count+=p->indices->count;
    }
    assert(meshes==2 && vertices_count==20452 && indices_count==21272*3);
    float (*vertices)[3]=malloc(vertices_count*sizeof(*vertices));size_t* indices=malloc(indices_count*sizeof(*indices));assert(vertices && indices);
    float lo[]={INFINITY,INFINITY,INFINITY},hi[]={-INFINITY,-INFINITY,-INFINITY};size_t base=0,at=0,body_first=0,body_count=0;
    for(size_t n=0;n<data->nodes_count;n++) {
        cgltf_node* node=&data->nodes[n];if(!node->mesh)continue;
        cgltf_primitive* p=node->mesh->primitives;const cgltf_accessor* positions=cgltf_find_accessor(p,cgltf_attribute_type_position,0);
        if(!strcmp(node->name,"power_box_01_box")){body_first=base;body_count=positions->count;assert(p->indices->count==19856*3);}
        float transform[16];cgltf_node_transform_world(node,transform);
        for(size_t v=0;v<positions->count;v++) {
            float local[3];assert(cgltf_accessor_read_float(positions,v,local,3));
            for(int k=0;k<3;k++) {
                float x=transform[k]*local[0]+transform[4+k]*local[1]+transform[8+k]*local[2]+transform[12+k];
                assert(isfinite(x));vertices[base+v][k]=x;lo[k]=fminf(lo[k],x);hi[k]=fmaxf(hi[k],x);
            }
        }
        for(size_t i=0;i<p->indices->count;i++){size_t ix=cgltf_accessor_read_index(p->indices,i);assert(ix<positions->count);indices[at++]=base+ix;}
        base+=positions->count;
    }
    assert(base==vertices_count && at==indices_count && body_count==19196 && fabsf(lo[2])<1e-6f);
    assert(fabsf(hi[0]-lo[0]-.4613243f)<1e-6f && fabsf(hi[1]-lo[1]-.5031428f)<1e-6f && fabsf(hi[2]-lo[2]-.3989851f)<1e-6f);
    float center[3],half[3];for(int k=0;k<3;k++){center[k]=(lo[k]+hi[k])*.5f;half[k]=(hi[k]-lo[k])*.5f;}
    puts("// Generated by tools/import_motel_cabinet.c; original two meshes, full static scene transforms, metres.");
    puts("static b3Vec3 cabinet_vertices[]={");
    for(size_t v=0;v<vertices_count;v++)printf("{%.9ef,%.9ef,%.9ef},\n",vertices[v][0]-center[0],vertices[v][1]-center[1],vertices[v][2]-center[2]);
    puts("};\nstatic int32_t cabinet_indices[]={");
    for(size_t i=0;i<indices_count;i++){printf("%zu,",indices[i]);if(i%24==23)puts("");}puts("};");
    const cgltf_pbr_metallic_roughness* m=&data->materials[0].pbr_metallic_roughness;
    printf("static const SwatMotelMaterial cabinet_materials[]={{%.9ef,%.9ef}};\n",m->roughness_factor,m->metallic_factor);
    printf("static const SwatMotelAsset cabinet_asset={\"%s\",{%.9ef,%.9ef,%.9ef},{%.9ef,%.9ef,%.9ef},cabinet_vertices,%zu,cabinet_indices,21272,cabinet_materials,1};\n",file,center[0],center[1],center[2],half[0],half[1],half[2],vertices_count);
    // Four actual vertices on the modeled body's rear rim. These are geometric
    // support references for the game, not certified fasteners or mounting holes.
    puts("static const b3Vec3 cabinet_rear_contacts[]={");
    for(int corner=0;corner<4;corner++) {
        float target_x=corner&1 ? .17f : -.17f,target_y=corner&2 ? .25f : -.25f,best=INFINITY;size_t selected=vertices_count;
        for(size_t v=body_first;v<body_first+body_count;v++)if(fabsf(vertices[v][2])<1e-6f) {
            float dx=vertices[v][0]-target_x,dy=vertices[v][1]-target_y,distance=dx*dx+dy*dy;
            if(distance<best){best=distance;selected=v;}
        }
        assert(selected<vertices_count && best<.0001f);
        printf("{%.9ef,%.9ef,%.9ef},\n",vertices[selected][0],vertices[selected][1],vertices[selected][2]);
    }
    puts("};");free(indices);free(vertices);cgltf_free(data);
}
