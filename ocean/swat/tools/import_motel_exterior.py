#!/usr/bin/env python3
"""Generate motel_exterior_data.h from the Blender-built exterior kit.

  python3 ocean/swat/tools/import_motel_exterior.py

Inputs : ocean/swat/assets/environment/motel_exterior/exterior_kit.glb
         ocean/swat/assets/environment/motel_exterior/placements.json
         (both written by tools/blender/motel_exterior_kit.py)
Output : ocean/swat/motel_exterior_data.h
         (--arch: architecture_kit.glb + architecture_placements.json ->
          ocean/swat/motel_exterior_arch_data.h)

Raylib 5.5 flattens a glTF into meshes in node order, one mesh per triangle
primitive, and stores glTF material i at index i+1 (slot 0 is its default).
This script reproduces that order so the renderer can draw one piece as a
contiguous mesh range and find the library materials by name. It never runs
Blender or executes anything from the asset.
"""
import hashlib, json, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SWAT = os.path.dirname(HERE)
KIT = os.path.join(SWAT, 'assets/environment/motel_exterior/exterior_kit.glb')
PLACEMENTS = os.path.join(SWAT, 'assets/environment/motel_exterior/placements.json')
OUT = os.path.join(SWAT, 'motel_exterior_data.h')


def glb_json(path):
    data = open(path, 'rb').read()
    magic, version, _ = struct.unpack('<4sII', data[:12])
    assert magic == b'glTF' and version == 2, path
    n, kind = struct.unpack('<I4s', data[12:20])
    assert kind == b'JSON'
    return json.loads(data[20:20 + n]), hashlib.sha256(data).hexdigest()


def main():
    gltf, digest = glb_json(KIT)
    manifest = json.load(open(PLACEMENTS))
    pieces, mesh = {}, 0
    library = {}
    for node in gltf['nodes']:
        if 'mesh' not in node:
            continue
        for k in ('matrix', 'rotation', 'scale', 'translation'):
            assert k not in node, f"{node['name']}: pieces must keep identity node transforms"
        prims = gltf['meshes'][node['mesh']]['primitives']
        assert all(p.get('mode', 4) == 4 for p in prims)
        pieces[node['name']] = (mesh, len(prims))
        if node['name'].startswith('L_'):
            assert len(prims) == 1
            library[node['name'][2:]] = prims[0]['material'] + 1
        mesh += len(prims)
    order = [name for name in pieces if name.startswith('P_')]
    index = {name: i for i, name in enumerate(order)}
    lines = [
        '// Generated by tools/import_motel_exterior.py from',
        '// assets/environment/motel_exterior/exterior_kit.glb and placements.json.',
        f'// exterior_kit.glb sha256 {digest}',
        '// Presentation only: no colliders, navigation, cover or protocol data.',
        '#ifndef SWAT_MOTEL_EXTERIOR_DATA_H',
        '#define SWAT_MOTEL_EXTERIOR_DATA_H',
        '#define SWAT_EXTERIOR_KIT_FILE "motel_exterior/exterior_kit.glb"',
        f'#define SWAT_EXTERIOR_KIT_MESHES {mesh}',
        f'#define SWAT_EXTERIOR_KIT_MATERIALS {len(gltf["materials"])}',
        f'#define SWAT_EXTERIOR_PIECES {len(order)}',
        f'#define SWAT_EXTERIOR_LIBRARY {len(library)}',
        f'#define SWAT_EXTERIOR_PLACEMENTS {len(manifest["placements"])}',
        'typedef struct SwatExteriorPiece { const char* name; int first,count; } SwatExteriorPiece;',
        'typedef struct SwatExteriorLibrary { const char* name; int material; } SwatExteriorLibrary;',
        'typedef struct SwatExteriorPlacement { int piece,owner; float x,y,z,yaw,sx,sy,sz; bool wall,roof; } SwatExteriorPlacement;',
        'static const SwatExteriorPiece swat_exterior_pieces[SWAT_EXTERIOR_PIECES]={',
    ]
    lines += [f'    {{"{n}",{pieces[n][0]},{pieces[n][1]}}},' for n in order]
    lines += ['};', 'static const SwatExteriorLibrary swat_exterior_library[SWAT_EXTERIOR_LIBRARY]={']
    lines += [f'    {{"{n}",{m}}},' for n, m in library.items()]
    lines += ['};', 'static const SwatExteriorPlacement swat_exterior_placements[SWAT_EXTERIOR_PLACEMENTS]={']
    f = lambda v: repr(float(v)) + 'f'
    for p in manifest['placements']:
        x, y, z = p['origin']; sx, sy, sz = p['scale']
        lines.append(f'    {{{index[p["piece"]]},{int(p["owner"])},{f(x)},{f(y)},{f(z)},{f(p["yaw"])},{f(sx)},{f(sy)},{f(sz)},'
                     f'{"true" if p["mount"] == "wall" else "false"},{"true" if p["roof"] else "false"}}}, // {p["piece"]}')
    lines += ['};', '#endif', '']
    open(OUT, 'w').write('\n'.join(lines))
    print(f'wrote {OUT}: {len(order)} pieces, {mesh} meshes, {len(library)} library materials, {len(manifest["placements"])} placements')


ARCH_KIT = os.path.join(SWAT, 'assets/environment/motel_exterior/architecture_kit.glb')
ARCH_PLACEMENTS = os.path.join(SWAT, 'assets/environment/motel_exterior/architecture_placements.json')
ARCH_OUT = os.path.join(SWAT, 'motel_exterior_arch_data.h')


def arch():
    """motel_exterior_arch_data.h: one placement per architecture piece, with
    its mesh range; section mounts carry the authoritative section centre."""
    gltf, digest = glb_json(ARCH_KIT)
    manifest = json.load(open(ARCH_PLACEMENTS))
    pieces, mesh = {}, 0
    for node in gltf['nodes']:
        if 'mesh' not in node:
            continue
        for k in ('matrix', 'rotation', 'scale', 'translation'):
            assert k not in node, f"{node['name']}: pieces must keep identity node transforms"
        prims = gltf['meshes'][node['mesh']]['primitives']
        assert all(p.get('mode', 4) == 4 for p in prims)
        pieces[node['name']] = (mesh, len(prims))
        mesh += len(prims)
    f = lambda v: repr(float(v)) + 'f'
    lines = [
        '// Generated by tools/import_motel_exterior.py --arch from',
        '// assets/environment/motel_exterior/architecture_kit.glb and architecture_placements.json.',
        f'// architecture_kit.glb sha256 {digest}',
        '// Presentation only: no colliders, navigation, cover or protocol data.',
        '#ifndef SWAT_MOTEL_EXTERIOR_ARCH_DATA_H',
        '#define SWAT_MOTEL_EXTERIOR_ARCH_DATA_H',
        '#define SWAT_ARCH_KIT_FILE "motel_exterior/architecture_kit.glb"',
        f'#define SWAT_ARCH_KIT_MESHES {mesh}',
        f'#define SWAT_ARCH_KIT_MATERIALS {len(gltf["materials"])}',
        f'#define SWAT_ARCH_PLACEMENTS {len(manifest["placements"])}',
        f'#define SWAT_ARCH_SUPPRESS {len(manifest["suppress"])}',
        '// section: owner is the wall instance; drawn with the skin section whose centre is (x,y,z).',
        'typedef struct SwatArchPlacement { int first,count,owner; float x,y,z; bool section,roof; } SwatArchPlacement;',
        'static const char* const swat_arch_suppress[SWAT_ARCH_SUPPRESS]={' + ','.join(f'"{n}"' for n in manifest['suppress']) + '};',
        'static const SwatArchPlacement swat_arch_placements[SWAT_ARCH_PLACEMENTS]={',
    ]
    for p in manifest['placements']:
        first, count = pieces[p['piece']]
        x, y, z = p['origin']
        lines.append(f'    {{{first},{count},{int(p["owner"])},{f(x)},{f(y)},{f(z)},'
                     f'{"true" if p["mount"] == "section" else "false"},{"true" if p["roof"] else "false"}}}, // {p["piece"]}')
    lines += ['};', '#endif', '']
    open(ARCH_OUT, 'w').write('\n'.join(lines))
    print(f'wrote {ARCH_OUT}: {len(manifest["placements"])} placements, {mesh} meshes')


if __name__ == '__main__':
    sys.exit(arch() if '--arch' in sys.argv else main())
