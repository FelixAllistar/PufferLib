// Preserve the delivered source geometry; flatten node transforms for collision.
// From ocean/swat: clang tools/import_motel_bag.c -lm -o <temporary importer>.
#include "../vendor/cgltf_private.h"
#include <assert.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
int main(void) {
    const char* file="trashbag_floor_centered_1k.glb";
    char path[256];snprintf(path,sizeof(path),"assets/environment/motel_props/%s",file);
    cgltf_options options={0};cgltf_data* data=NULL;
    assert(cgltf_parse_file(&options,path,&data)==cgltf_result_success);
    assert(cgltf_load_buffers(&options,data,path)==cgltf_result_success && cgltf_validate(data)==cgltf_result_success);
    assert(data->materials_count==1);int meshes=0;
    puts("// Generated by tools/import_motel_bag.c; original source triangles, full scene transforms, metres.");
    for(size_t n=0;n<data->nodes_count;n++) {
        cgltf_node* node=&data->nodes[n];if(!node->mesh)continue;
        assert(++meshes==1 && node->mesh->primitives_count==1);
        cgltf_primitive* prim=&node->mesh->primitives[0];assert(prim->indices && prim->type==cgltf_primitive_type_triangles && prim->indices->count==4482*3);
        const cgltf_accessor* positions=cgltf_find_accessor(prim,cgltf_attribute_type_position,0);assert(positions);
        float matrix[16];cgltf_node_transform_world(node,matrix);
        size_t count=positions->count;float (*vertices)[3]=malloc(count*sizeof(*vertices));assert(vertices);
        float lo[]={INFINITY,INFINITY,INFINITY},hi[]={-INFINITY,-INFINITY,-INFINITY};size_t lowest=0;
        for(size_t v=0;v<count;v++) {
            float local[3];assert(cgltf_accessor_read_float(positions,v,local,3));
            for(int k=0;k<3;k++) {
                float x=matrix[k]*local[0]+matrix[4+k]*local[1]+matrix[8+k]*local[2]+matrix[12+k];
                assert(isfinite(x));vertices[v][k]=x;lo[k]=fminf(lo[k],x);hi[k]=fmaxf(hi[k],x);
            }
            if(vertices[v][1]<vertices[lowest][1])lowest=v;
        }
        assert(fabsf(lo[1])<1e-6f && fabsf(hi[1]-.5749994f)<1e-6f);
        float center[3],half[3];for(int k=0;k<3;k++){center[k]=(lo[k]+hi[k])*.5f;half[k]=(hi[k]-lo[k])*.5f;}
        puts("static b3Vec3 bag_vertices[]={");
        for(size_t v=0;v<count;v++)printf("{%.9ef,%.9ef,%.9ef},\n",vertices[v][0]-center[0],vertices[v][1]-center[1],vertices[v][2]-center[2]);
        puts("};\nstatic int32_t bag_indices[]={");
        for(size_t i=0;i<prim->indices->count;i++){size_t ix=cgltf_accessor_read_index(prim->indices,i);assert(ix<count);printf("%zu,",ix);if(i%24==23)puts("");}
        puts("};");const cgltf_pbr_metallic_roughness* m=&data->materials[0].pbr_metallic_roughness;
        printf("static const SwatMotelMaterial bag_materials[]={{%.9ef,%.9ef}};\n",m->roughness_factor,m->metallic_factor);
        printf("static const SwatMotelAsset bag_asset={\"%s\",{%.9ef,%.9ef,%.9ef},{%.9ef,%.9ef,%.9ef},bag_vertices,%zu,bag_indices,4482,bag_materials,1};\n",file,center[0],center[1],center[2],half[0],half[1],half[2],count);
        printf("static const b3Vec3 bag_floor_contact[]={ {%.9ef,%.9ef,%.9ef} };\n",vertices[lowest][0],vertices[lowest][1],vertices[lowest][2]);
        free(vertices);
    }
    assert(meshes==1);cgltf_free(data);
}
