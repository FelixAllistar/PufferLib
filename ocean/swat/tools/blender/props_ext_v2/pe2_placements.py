#!/usr/bin/env python3
"""Writes ocean/swat/motel_props_ext_v2_data.h from placements.json.
Placement: [prop, x, y, z, yaw_deg, scale, shadow]. Engine metres, +Y up;
yaw turns the prop's +X front towards (cos yaw, 0, -sin yaw)."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SWAT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
d = json.load(open(os.path.join(SWAT, "assets", "environment", "motel_props_ext_v2", "placements.json")))
props = d["props"]; rows = d["placements"]
out = ["// Generated by tools/blender/props_ext_v2/pe2_placements.py from",
       "// assets/environment/motel_props_ext_v2/placements.json. Presentation only.",
       "#ifndef SWAT_MOTEL_PROPS_EXT_V2_DATA_H", "#define SWAT_MOTEL_PROPS_EXT_V2_DATA_H",
       "#define SWAT_PE2_PROPS %d" % len(props), "#define SWAT_PE2_PLACEMENTS %d" % len(rows),
       "typedef struct SwatPe2Placement { int prop; float x,y,z,yaw,scale; bool shadow; } SwatPe2Placement;",
       "static const char* const swat_pe2_props[SWAT_PE2_PROPS]={"]
out += ['    "%s",' % p for p in props] + ["};", "static const SwatPe2Placement swat_pe2_placements[SWAT_PE2_PLACEMENTS]={"]
for r in rows:
    name, x, y, z, yaw, sc, sh = r[:7]
    out.append("    {%d,%.3ff,%.3ff,%.3ff,%.5ff,%.3ff,%s}, // %s%s" % (props.index(name), x, y, z, yaw * 3.141592653589793 / 180, sc, "true" if sh else "false", name, (" " + r[7]) if len(r) > 7 else ""))
out += ["};", "#endif", ""]
open(os.path.join(SWAT, "motel_props_ext_v2_data.h"), "w").write("\n".join(out))
print(len(props), "props", len(rows), "placements")
